# Extracts the fixed VP8 tables from the text of RFC 6386 into src/Zorg.Imaging/Codecs/Webp/Vp8Tables.cs, checking that
# each has the size the RFC declares. The RFC isn't committed; fetch it from https://www.rfc-editor.org/rfc/rfc6386.txt.
#   python -I scripts/extract-vp8-tables.py rfc6386.txt src/Zorg.Imaging/Codecs/Webp/Vp8Tables.cs
import re, sys
rfc = sys.argv[1]
out = sys.argv[2]
lines = open(rfc, encoding='utf-8').read().split('\n')

def table(start_pattern, occurrence, expected):
    hits = [i for i, l in enumerate(lines) if re.search(start_pattern, l)]
    i = hits[occurrence]
    text = []
    depth = 0
    started = False
    for line in lines[i:]:
        # Skip RFC page furniture.
        if re.match(r'^Bankoski, et al\.', line) or re.match(r'^RFC 6386 ', line) or '\f' in line:
            continue
        text.append(line)
        depth += line.count('{') - line.count('}')
        if '{' in line:
            started = True
        if started and depth <= 0 and '}' in line:
            break
    body = '\n'.join(text)
    body = body[body.index('=') + 1:] if '=' in body.split('{')[0] else body[body.index('{'):]
    body = re.sub(r'/\*.*?\*/', ' ', body, flags=re.S)
    body = re.sub(r'//[^\n]*', ' ', body)
    numbers = [int(n) for n in re.findall(r'-?\d+', body)]
    assert len(numbers) == expected, (start_pattern, len(numbers), expected)
    return numbers

tables = {
    'KeyFrameSubblockModeProbabilities': table(r'const Prob kf_bmode_prob \[num_intra_bmodes\] \[num_intra_bmodes\]', 1, 900),
    'CoefficientUpdateProbabilities': table(r'const Prob coeff_update_probs \[4\] \[8\] \[3\]', 0, 1056),
    'DefaultCoefficientProbabilities': table(r'const Prob default_coeff_probs \[4\] \[8\] \[3\]', 0, 1056),
    'DcQuantiser': table(r'static const int dc_qlookup\[QINDEX_RANGE\]', 0, 128),
    'AcQuantiser': table(r'static const int ac_qlookup\[QINDEX_RANGE\]', 0, 128),
}

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated>\n')
    f.write('// Tables from RFC 6386 (VP8 Data Format and Decoding Guide), sections 11.5, 13.4, 13.5 and 14.1,\n')
    f.write('// extracted by scripts/extract-vp8-tables.py from the RFC text. Do not edit by hand.\n')
    f.write('// </auto-generated>\n')
    f.write('using System;\n\nnamespace Zorg.Imaging.Codecs.Webp;\n\n')
    f.write('/// <summary>The fixed tables of VP8 key-frame decoding, as RFC 6386 gives them.</summary>\n')
    f.write('internal static class Vp8Tables\n{\n')
    for name, values in tables.items():
        kind = 'ushort' if 'Quantiser' in name else 'byte'
        f.write(f'    public static ReadOnlySpan<{kind}> {name} =>\n    [\n')
        for k in range(0, len(values), 16):
            f.write('        ' + ', '.join(str(v) for v in values[k:k + 16]) + ',\n')
        f.write('    ];\n\n')
    f.seek(f.tell() - 1)
    f.write('}\n')
print({k: len(v) for k, v in tables.items()})
print('kf_bmode first', tables['KeyFrameSubblockModeProbabilities'][:9])
print('default first', tables['DefaultCoefficientProbabilities'][:11], 'last', tables['DefaultCoefficientProbabilities'][-11:])
print('dc', tables['DcQuantiser'][:8], tables['DcQuantiser'][-3:], 'ac', tables['AcQuantiser'][:8], tables['AcQuantiser'][-3:])
